// Keep Korean particles outside the highlight and reject matches inside other words.
const suffix = "에서부터|에게서는|에게서|으로부터|으로는|에서는|이라고|이라는|이라서|이지만|이었어요|이에요|입니다|처럼|마다|까지|밖에|이나|라도|만큼|에게|한테|부터|보다|으로|에서|했고|했어요|했나요|해요|해서|하며|하는|하다|하면|하고|하세요|하던|한|할|해|의|은|는|이|가|을|를|과|와|로|에|도|만|인|란|들";
const escapePattern = (term) => term.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export function createVocabulary(custom = []) {
  const meanings = new Map(Object.entries(commonMeanings));
  for (const { term, meaning } of custom) meanings.set(term, meaning);
  const words = [...meanings.keys()].sort((a, b) => b.length - a.length).map(escapePattern);
  const pattern = new RegExp(`(?<![\\p{L}\\p{N}])(${words.join("|")})(?=(?:(?:${suffix}))?(?![\\p{L}\\p{N}]))`, "gu");
  return (text, seen = new Set()) => {
    const parts = [];
    let start = 0;
    for (const match of text.matchAll(pattern)) {
      const [term] = match;
      if (seen.has(term)) continue;
      seen.add(term);
      if (match.index > start) parts.push(text.slice(start, match.index));
      parts.push({ term, meaning: meanings.get(term) });
      start = match.index + term.length;
    }
    if (start < text.length) parts.push(text.slice(start));
    return parts;
  };
}
